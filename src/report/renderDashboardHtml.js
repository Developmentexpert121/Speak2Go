const { esc, num } = require("./escapeHtml");
const { getBlueprint } = require("../config/examBlueprint");

/**
 * Renders the full analytical dashboard: exam result + report object in, a
 * single self-contained HTML document out.
 *
 * Self-contained on purpose — no CDN fonts, no external CSS, no JS
 * dependencies. That means it can be dropped into an iframe in the Speak2Go
 * UI, emailed as a file, or handed straight to Puppeteer for the PDF, with
 * identical output in all three.
 *
 * @param {object} examResult - output of evaluateFullExam()
 * @param {object} report     - output of buildReportObject()
 * @param {object} meta       - { studentName, examLevel, dateExecuted, examId }
 */
function renderDashboardHtml(examResult, report, meta = {}) {
  const results = examResult.question_results || [];
  const blueprint = safeBlueprint(examResult.level, examResult.exam_layout);

  const analytics = computeAnalytics(examResult, results, blueprint);

  return `<!DOCTYPE html>
<html lang="en"><head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(meta.studentName || "Student")} — Oral Exam Evaluation</title>
<style>${STYLES}</style>
</head>
<body>
<div class="page">

  ${renderHeader(examResult, meta)}
  ${renderStatStrip(examResult, analytics)}
  ${renderPipeline(analytics)}

  <div class="grid-2">
    ${renderPartBreakdown(analytics)}
    ${renderCriterionProfile(analytics)}
  </div>

  ${renderQuestions(results, analytics)}
  ${renderDeductions(report)}
  ${renderRecommendations(report)}

  <footer class="footer">
    Generated by the Speak2Go automated COBE evaluation module ·
    ${esc(new Date().toISOString().slice(0, 16).replace("T", " "))} UTC ·
    Scores are machine-generated and intended to support, not replace, examiner judgement.
  </footer>
</div>
</body></html>`;
}

/* ------------------------------------------------------------------ *
 * Derived analytics
 * ------------------------------------------------------------------ */

/**
 * The slot list to lay the report out against.
 *
 * Prefer the layout the exam was actually built from (examResult.exam_layout,
 * as produced by examBlueprint.inspectLesson). Part B is one question in the
 * 2019-2022 lessons and a two-question set in the 2023 ones, so falling back
 * to the default blueprint on a 2023 exam would render an empty "Part B -
 * Project Presentation" slot and hide the two questions the student answered.
 */
function safeBlueprint(level, examLayout) {
  if (Array.isArray(examLayout) && examLayout.length) return examLayout;
  try {
    return getBlueprint(level);
  } catch {
    return [];
  }
}

function computeAnalytics(examResult, results, blueprint) {
  const byId = Object.fromEntries(results.map((r) => [String(r.question_id), r]));

  // Points per exam part, against what each part is worth
  const partTotals = {};
  for (const bp of blueprint) {
    if (!partTotals[bp.part]) partTotals[bp.part] = { part: bp.part, possible: 0, earned: 0, questions: [] };
    partTotals[bp.part].possible += bp.points;
    const r = byId[bp.question_id];
    if (r) {
      partTotals[bp.part].earned += (r.final_question_score / 100) * (r.weight || bp.points);
    }
    partTotals[bp.part].questions.push({ ...bp, result: r || null });
  }

  // Average score per rubric criterion, across every scored question
  const criterionAcc = {};
  for (const r of results) {
    for (const c of r.criterion_breakdown || []) {
      if (!criterionAcc[c.criterion_name]) criterionAcc[c.criterion_name] = { total: 0, n: 0, weight: c.weight };
      criterionAcc[c.criterion_name].total += c.criterion_score;
      criterionAcc[c.criterion_name].n += 1;
    }
  }
  const criterionAverages = Object.entries(criterionAcc)
    .map(([name, v]) => ({ name, average: v.total / v.n, weight: v.weight }))
    .sort((a, b) => a.average - b.average);

  const scored = results.filter((r) => (r.criterion_breakdown || []).length > 0);
  const deductionCount = results.reduce((s, r) => s + (r.deductions || []).length, 0);

  const fluencyLevels = results
    .map((r) => r.audio_metrics && r.audio_metrics.fluencyLevel)
    .filter((n) => typeof n === "number");
  const avgFluency = fluencyLevels.length
    ? fluencyLevels.reduce((a, b) => a + b, 0) / fluencyLevels.length
    : null;

  const totalSpeech = results.reduce(
    (s, r) => s + ((r.audio_metrics && r.audio_metrics.totalDurationSeconds) || 0),
    0
  );

  return {
    parts: Object.values(partTotals),
    criterionAverages,
    scoredCount: scored.length,
    attemptedCount: results.length,
    blueprintCount: blueprint.length || results.length,
    unattempted: examResult.unattempted_questions || [],
    deductionCount,
    avgFluency,
    totalSpeech,
    weakestCriterion: criterionAverages[0] || null,
    strongestCriterion: criterionAverages[criterionAverages.length - 1] || null,
  };
}

