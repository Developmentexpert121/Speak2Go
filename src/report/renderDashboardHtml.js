const band = (s) => (s >= 85 ? "high" : s >= 60 ? "mid" : "low");

function renderHeader(examResult, meta) {
  const score = Number(examResult.overall_score);
  const pct = Number.isFinite(score) ? Math.max(0, Math.min(100, score)) : 0;
  const R = 52;
  const C = 2 * Math.PI * R;

  return `
  <header class="header">
    <div class="header-id">
      <div class="eyebrow">Automated Oral Exam Evaluation</div>
      <h1>${esc(meta.studentName || "Student")}</h1>
      <div class="header-meta">
        ${meta.examLevel ? `<span class="tag">${esc(meta.examLevel)}</span>` : ""}
        ${examResult.level ? `<span class="tag tag-quiet">${esc(examResult.level)}</span>` : ""}
        ${meta.dateExecuted ? `<span class="dot">·</span><span>${esc(meta.dateExecuted)}</span>` : ""}
        ${meta.examId ? `<span class="dot">·</span><span class="mono">${esc(meta.examId)}</span>` : ""}
      </div>
    </div>

    <div class="score-dial band-${band(pct)}">
      <svg viewBox="0 0 128 128" width="128" height="128" role="img" aria-label="Overall score ${num(score)} out of 100">
        <circle class="dial-track" cx="64" cy="64" r="${R}" />
        <circle class="dial-value" cx="64" cy="64" r="${R}"
                stroke-dasharray="${C.toFixed(1)}"
                stroke-dashoffset="${(C * (1 - pct / 100)).toFixed(1)}"
                transform="rotate(-90 64 64)" />
      </svg>
      <div class="score-inner">
        <div class="score-num">${num(score)}</div>
        <div class="score-den">out of 100</div>
      </div>
    </div>
  </header>`;
}

function renderStatStrip(examResult, a) {
  const fluencyText = a.avgFluency === null ? "—" : `${a.avgFluency.toFixed(1)} / 4`;
  const mins = Math.floor(a.totalSpeech / 60);
  const secs = Math.round(a.totalSpeech % 60);

  const stats = [
    {
      label: "Points earned",
      value: `${num(examResult.points_earned, 1)}`,
      sub: `of ${esc(examResult.points_possible ?? 100)} available`,
    },
    {
      label: "Questions scored",
      value: `${a.scoredCount} / ${a.blueprintCount}`,
      sub: a.unattempted.length
        ? `${a.unattempted.length} never attempted`
        : a.scoredCount < a.attemptedCount
          ? `${a.attemptedCount - a.scoredCount} zeroed by penalty`
          : "all questions scored",
      tone: a.scoredCount < a.blueprintCount ? "warn" : "ok",
    },
    {
      label: "Deductions applied",
      value: String(a.deductionCount),
      sub: a.deductionCount ? "see breakdown below" : "none",
      tone: a.deductionCount ? "warn" : "ok",
    },
    {
      label: "Average fluency",
      value: fluencyText,
      sub: `${mins}m ${secs}s of speech`,
    },
  ];

  return `
  <section class="stat-strip">
    ${stats
      .map(
        (s) => `
      <div class="stat ${s.tone ? "stat-" + s.tone : ""}">
        <div class="stat-label">${esc(s.label)}</div>
        <div class="stat-value">${esc(s.value)}</div>
        <div class="stat-sub">${esc(s.sub)}</div>
      </div>`
      )
      .join("")}
  </section>`;
}

/**
 * The processing pipeline, rendered as a flow so a teacher (or the client)
 * can see exactly which stages produced the number at the top — and, more
 * importantly, which stages are deterministic rules versus model judgement.
 */
function renderPipeline(a) {
  const stages = [
    { n: "1", name: "Audio intake", detail: "Student recording", kind: "io" },
    { n: "2", name: "Speech-to-text", detail: "Deepgram, word timings", kind: "io" },
    { n: "3", name: "Speech metrics", detail: "Pauses · WPM · fillers", kind: "det" },
    { n: "4", name: "Rubric scoring", detail: "9 sub-criteria × 4 levels", kind: "llm" },
    { n: "5", name: "Aggregation", detail: "Criterion → question", kind: "det" },
    { n: "6", name: "Penalties", detail: "Coverage · time · flags", kind: "det" },
    { n: "7", name: "Report", detail: "Scored out of 100", kind: "out" },
  ];

  return `
  <section class="card pipeline-card">
    <div class="card-head">
      <h2>Evaluation pipeline</h2>
      <div class="legend">
        <span class="lg lg-det"></span> Deterministic rule
        <span class="lg lg-llm"></span> Model judgement
        <span class="lg lg-io"></span> External service
      </div>
    </div>
    <div class="pipeline">
      ${stages
        .map(
          (s, i) => `
        <div class="stage stage-${s.kind}">
          <div class="stage-n">${esc(s.n)}</div>
          <div class="stage-name">${esc(s.name)}</div>
          <div class="stage-detail">${esc(s.detail)}</div>
        </div>
        ${i < stages.length - 1 ? `<div class="stage-arrow" aria-hidden="true"></div>` : ""}`
        )
        .join("")}
    </div>
    <p class="pipeline-note">
      Only stage 4 involves model judgement, and it is constrained to picking one of four
      fixed rubric levels per sub-criterion. Every score-affecting calculation after that
      point — weighting, coverage deductions, time bands, and the 0-for-section rules — is
      deterministic and reproducible.
    </p>
  </section>`;
}

function renderPartBreakdown(a) {
  const partNames = { A: "Part A · Personal Response", B: "Part B · Project Presentation", C: "Part C · Audio-Visual" };

  if (!a.parts.length) return `<section class="card"><div class="card-head"><h2>Part breakdown</h2></div><p class="empty">No part data.</p></section>`;

  return `
  <section class="card">
    <div class="card-head"><h2>Points by exam part</h2></div>
    <div class="parts">
      ${a.parts
        .map((p) => {
          const pct = p.possible ? (p.earned / p.possible) * 100 : 0;
          return `
        <div class="part-row">
          <div class="part-top">
            <span class="part-name">${esc(partNames[p.part] || "Part " + p.part)}</span>
            <span class="part-points"><strong>${num(p.earned)}</strong> / ${esc(p.possible)}</span>
          </div>
          <div class="bar">
            <div class="bar-fill band-${band(pct)}" style="width:${pct.toFixed(1)}%"></div>
          </div>
        </div>`;
        })
        .join("")}
    </div>
  </section>`;
}

function renderCriterionProfile(a) {
  if (!a.criterionAverages.length) {
    return `<section class="card"><div class="card-head"><h2>Criterion profile</h2></div>
      <p class="empty">No questions were scored against the rubric — every answer was zeroed by a penalty rule before evaluation.</p></section>`;
  }

  return `
  <section class="card">
    <div class="card-head">
      <h2>Criterion profile</h2>
      <span class="card-sub">averaged across scored questions</span>
    </div>
    <div class="criteria">
      ${a.criterionAverages
        .map(
          (c) => `
        <div class="crit-row">
          <div class="crit-name">${esc(c.name)} <span class="crit-weight">${num(c.weight * 100, 0)}%</span></div>
          <div class="bar bar-sm"><div class="bar-fill band-${band(c.average)}" style="width:${Math.max(0, Math.min(100, c.average)).toFixed(1)}%"></div></div>
          <div class="crit-val">${num(c.average)}</div>
        </div>`
        )
        .join("")}
    </div>
    ${
      a.weakestCriterion && a.strongestCriterion && a.criterionAverages.length > 1
        ? `<p class="insight">Weakest area is <strong>${esc(a.weakestCriterion.name)}</strong>
             (${num(a.weakestCriterion.average)}), strongest is <strong>${esc(a.strongestCriterion.name)}</strong>
             (${num(a.strongestCriterion.average)}).</p>`
        : ""
    }
  </section>`;
}

function renderQuestions(results, a) {
  const unattemptedCards = a.unattempted
    .map(
      (u) => `
    <article class="card q-card q-missing">
      <div class="q-head">
        <span class="q-id">Q${esc(u.question_id)}</span>
        <span class="q-desc">${esc(u.description)}</span>
        <span class="q-score band-low">0.0</span>
      </div>
      <div class="q-flag">Not attempted — forfeits ${esc(u.points_forfeited)} points.</div>
    </article>`
    )
    .join("");

  return `
  <section class="section">
    <h2 class="section-title">Question-by-question</h2>
    ${results.map(renderQuestionCard).join("")}
    ${unattemptedCards}
  </section>`;
}

function renderQuestionCard(r) {
  const m = r.audio_metrics || {};
  const zeroed = !(r.criterion_breakdown || []).length;

  const metricChips = [
    m.totalDurationSeconds != null ? `${num(m.totalDurationSeconds, 0)}s` : null,
    m.wpm ? `${esc(m.wpm)} wpm` : null,
    m.pauseCount != null ? `${esc(m.pauseCount)} long pause${m.pauseCount === 1 ? "" : "s"}` : null,
    m.fillerWordCount != null ? `${esc(m.fillerWordCount)} fillers` : null,
    m.fluencyLevel ? `fluency ${esc(m.fluencyLevel)}/4` : null,
  ].filter(Boolean);

  return `
  <article class="card q-card">
    <div class="q-head">
      <span class="q-id">Q${esc(r.question_id)}</span>
      <span class="q-desc">${esc(r.description)}</span>
      <span class="q-weight">${esc(r.weight)} pts</span>
      <span class="q-score band-${band(r.final_question_score)}">${num(r.final_question_score)}</span>
    </div>

    ${metricChips.length ? `<div class="chips">${metricChips.map((c) => `<span class="chip">${c}</span>`).join("")}</div>` : ""}

    ${
      zeroed
        ? `<div class="q-flag">Zeroed by a penalty rule before rubric evaluation — no criterion scores were produced.</div>`
        : `<div class="criteria criteria-inline">
            ${(r.criterion_breakdown || [])
              .map(
                (c) => `
              <div class="crit-row">
                <div class="crit-name">${esc(c.criterion_name)} <span class="crit-weight">${num(c.weight * 100, 0)}%</span></div>
                <div class="bar bar-sm"><div class="bar-fill band-${band(c.criterion_score)}" style="width:${Math.max(0, Math.min(100, c.criterion_score)).toFixed(1)}%"></div></div>
                <div class="crit-val">${num(c.criterion_score)}</div>
              </div>
              ${
                (c.sub_criteria || []).length
                  ? `<div class="subs">${c.sub_criteria
                      .map(
                        (s) => `<span class="sub band-${band(s.score)}">${esc(s.name)} <b>${esc(s.score)}</b></span>`
                      )
                      .join("")}</div>`
                  : ""
              }`
              )
              .join("")}
          </div>`
    }

    ${
      (r.deductions || []).length
        ? `<div class="q-deductions">${r.deductions
            .map((d) => `<span class="ded">−${esc(d.deduction)}% · ${esc(d.reason)}</span>`)
            .join("")}</div>`
        : ""
    }
    ${r.coverage_note ? `<div class="q-note">${esc(r.coverage_note)}</div>` : ""}
    ${
      r.transcript
        ? `<details class="transcript">
             <summary>Transcript (${esc(String(r.transcript).trim().split(/\s+/).length)} words)</summary>
             <p>${esc(r.transcript)}</p>
           </details>`
        : ""
    }
  </article>`;
}

function renderDeductions(report) {
  const rows = report.deductionsTable || [];
  return `
  <section class="card">
    <div class="card-head"><h2>Deductions</h2></div>
    ${
      rows.length
        ? `<table class="table">
            <thead><tr><th>Question</th><th>Reason</th><th class="right">Deduction</th></tr></thead>
            <tbody>
              ${rows
                .map(
                  (d) => `<tr>
                    <td class="mono">Q${esc(d.questionId)}</td>
                    <td>${esc(d.reason)}</td>
                    <td class="right neg">−${esc(d.deduction)}%</td>
                  </tr>`
                )
                .join("")}
            </tbody>
          </table>
          <p class="table-note">Deductions within a question are not additive — the largest applicable
          deduction is applied, per the Ministry rubric's "0% for the entire section" wording.</p>`
        : `<p class="empty">No deductions were applied.</p>`
    }
  </section>`;
}

function renderRecommendations(report) {
  return `
  <section class="card reco-card">
    <div class="card-head"><h2>Teacher recommendations</h2></div>
    <div class="reco">${esc(report.teacherRecommendations) || "—"}</div>
  </section>`;
}

